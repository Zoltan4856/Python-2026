prvnicislo = int(input("Zadej prvni cislo"))

druhecislo  = int(input("Zadej druhe cislo"))


soucet = prvnicislo + druhecislo

rozdil = prvnicislo - druhecislo

soucin = prvnicislo * druhecislo

podil = prvnicislo / druhecislo


print(f"Soucet {prvnicislo} a {druhecislo} je {soucet} \n rozdil {prvnicislo} a {druhecislo} je {rozdil}")
print(f"Soucin {prvnicislo} a {druhecislo} je {soucin} \n podil {prvnicislo } a {druhecislo} je {podil}")